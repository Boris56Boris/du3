# Age 2: en mission for hver regional kulturgruppe (spillerlande), og en unik mission for hvert af de 20 lande.
from framework import *

AGE2 = 'du_mission_age2_trigger = yes'


def gruppe(group, icon, name, desc, style, tasks):
    vis = ('culture ?= { has_culture_group = culture_group:%s_group }\n'
           'du_mission_unik_age2_trigger = no\ndu_mission_spillerland_trigger = yes') % group
    return Mission('du_m2_%s' % group, icon, name, desc, style, vis, AGE2, tasks, chance=4000)


def unik(tags, icon, name, desc, style, tasks):
    key = 'du_m2_%s' % tags[0].lower()
    vis = 'has_or_had_tag = %s' % tags[0] if len(tags) == 1 else \
        'OR = {\n%s\n}' % '\n'.join('\thas_or_had_tag = %s' % t for t in tags)
    return Mission(key, icon, name, desc, style, vis, AGE2, tasks, chance=6000)


def formable(tag, *areas, frac=0.8):
    return eller(raa('has_or_had_tag = %s' % tag), *[omraade(a, frac) for a in areas])


