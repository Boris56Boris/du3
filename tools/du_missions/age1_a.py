def tree(key, tags, icon, name, desc, style, tasks):
    vis = 'has_or_had_tag = %s' % tags[0] if len(tags) == 1 else \
        'OR = {\n%s\n}' % '\n'.join('\thas_or_had_tag = %s' % t for t in tags)
    return Mission(key, icon, name, desc, style, vis, 'always = yes', tasks)


